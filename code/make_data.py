def check(name, data, n_docs):
    docs = [d for d, _ in data]
    qs = [q for _, qq in data for q in qq]
    assert len(docs) == n_docs, f"{name}: 문서 {len(docs)}개 (기대 {n_docs})"
    assert len(set(docs)) == len(docs), f"{name}: 중복 문서"
    assert all(len(qq) == 3 for _, qq in data), f"{name}: 문서당 질의 3개가 아님"
    assert len(set(qs)) == len(qs), f"{name}: 중복 질의 {[q for q in qs if qs.count(q) > 1]}"
    return set(docs), set(qs)

ed, eq = check("eval", EVAL, 20)
td, tq = check("train", TRAIN, 94)
assert not (ed & td), f"평가·학습 문서 겹침: {ed & td}"
assert not (eq & tq), f"평가·학습 질의 겹침: {eq & tq}"

